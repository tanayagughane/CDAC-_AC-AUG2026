class a1{
	static byte a;
	static short b;
	static int c;
	static long d;
	static float e;
    static double f;
    static char g;
	static boolean h;
	static String s1;

 
}
public class IUninitializedVariables{
	public static void main(String[] args ){
		
		System.out.println("byte value: " + a1.a);
        System.out.println("short value: " + a1.b);
        System.out.println("int value: " + a1.c);
        System.out.println("long value: " + a1.d);
        System.out.println("float value: " + a1.e);
        System.out.println("double value: " + a1.f);
        System.out.println("char value: " + a1.g);
        System.out.println("boolean value: " + a1.h);
		System.out.println("string value: " + a1.s1);
		
	}
}